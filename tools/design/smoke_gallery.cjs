const path=require('node:path');
const kit=path.resolve(__dirname,'../../docs/design/village-kit');
const {chromium:pw}=require('playwright-core');
const chromium=require('@sparticuz/chromium').default;
(async()=>{
 const browser=await pw.launch({executablePath:process.env.BROWSER_EXECUTABLE_PATH || await chromium.executablePath(),args:chromium.args,headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(String(e)));page.on('response',r=>{if(r.status()>=400)errors.push(`${r.status()} ${r.url()}`)});
 await page.goto(process.env.GALLERY_URL || 'http://127.0.0.1:8000/',{waitUntil:'networkidle'});
 await page.waitForSelector('.card:nth-child(6)');
 if(await page.locator('.card').count()!==6)throw Error('Wrong card count');
 await page.locator('.card').last().scrollIntoViewIfNeeded();await page.waitForLoadState('networkidle');await page.evaluate(()=>scrollTo(0,0));
 if(!await page.locator('.art img').evaluateAll(imgs=>imgs.every(i=>i.complete&&i.naturalWidth>0)))throw Error('Broken artwork');
 await page.screenshot({path:path.join(kit,'evidence/gallery-desktop.png'),fullPage:true});
 await page.locator('#old').click();await page.waitForLoadState('networkidle');
 if(!await page.locator('.art img').evaluateAll(imgs=>imgs.every(i=>i.getAttribute('src').startsWith('baseline/'))))throw Error('Baseline toggle failed');
 await page.locator('#new').click();await page.selectOption('#size','small');
 if(await page.locator('.art img').first().evaluate(i=>Math.round(i.getBoundingClientRect().width))!==104)throw Error('104px preview failed');
 await page.locator('.art').first().click();
 if(!await page.locator('dialog').evaluate(d=>d.open))throw Error('Dialog not opened');
 const download=page.waitForEvent('download');await page.locator('#download512').click();const result=await download;
 if(!result.suggestedFilename().endsWith('.webp'))throw Error('Download invalid');
 await page.keyboard.press('Escape');if(await page.locator('dialog').evaluate(d=>d.open))throw Error('Escape failed');
 await page.setViewportSize({width:390,height:844});await page.selectOption('#size','full');
 await page.evaluate(()=>scrollTo(0,0));await page.screenshot({path:path.join(kit,'evidence/gallery-mobile.png'),fullPage:true});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile horizontal overflow');
 await page.locator('.art').first().click();await page.locator('.close').click();
 if(errors.length)throw Error(errors.join('\n'));
 console.log('PASS: 6 cards, loaded images, baseline toggle, 104px mode, dialog, download, Escape, close button, mobile viewport, no JS/HTTP errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
